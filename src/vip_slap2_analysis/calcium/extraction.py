"""Event-aligned extraction for soma calcium-imaging traces.

This module reads processed soma calcium traces from a SummaryLoCo MAT file,
reconstructs continuous per-DMD session traces, aligns them to corrected Bonsai
stimulus events, and writes mean, single-trial, and sequence-aligned calcium
packages to ``analysis/derived/calcium``.

The extraction pathway mirrors the glutamate event-alignment outputs where
possible, but operates on manually exported soma ROIs and can optionally apply
soma-QC masks generated by :mod:`vip_slap2_analysis.calcium.qc`.
"""
